package com.demonwav.mcdev.creator.custom.finalizers

import com.demonwav.mcdev.creator.custom.CreatorTemplateProcessor
import com.demonwav.mcdev.creator.custom.TemplateFile
import com.demonwav.mcdev.creator.custom.TemplateValidationReporter
import com.google.gson.Gson
import com.intellij.ide.util.projectWizard.WizardContext
import com.intellij.openapi.application.WriteAction
import com.intellij.openapi.diagnostic.thisLogger
import com.intellij.openapi.project.Project

/**
 * Generates template files at this point of the finalization, instead of before any finalizer runs. This allows
 * overwriting files created by other finalizers, such as a project generated by an external tool.
 *
 * The `files` property has the same format as the template descriptor's `files`.
 */
class GenerateFilesFinalizer : CreatorFinalizer {

    override fun validate(reporter: TemplateValidationReporter, properties: Map<String, Any>) {
        val files = properties["files"] as? List<*>
        if (files == null) {
            reporter.error("Missing list of 'files' to generate")
            return
        }

        for ((index, file) in files.withIndex()) {
            if (file !is Map<*, *>) {
                reporter.error("File #$index must be an object")
                continue
            }

            if (file["template"] !is String) {
                reporter.error("File #$index is missing its 'template'")
            }
            if (file["destination"] !is String) {
                reporter.error("File #$index is missing its 'destination'")
            }
        }
    }

    override suspend fun execute(
        context: WizardContext,
        project: Project,
        properties: Map<String, Any>,
        templateProperties: Map<String, Any?>
    ) {
        val template = context.getUserData(CreatorTemplateProcessor.LOADED_TEMPLATE_KEY)
        if (template == null) {
            thisLogger().error("No template available to generate files from")
            return
        }

        val gson = Gson()
        val files = (properties["files"] as List<*>)
            .map { gson.fromJson(gson.toJsonTree(it), TemplateFile::class.java) }
        val generatedFiles = CreatorTemplateProcessor.writeFiles(
            template,
            files,
            templateProperties,
            context.projectDirectory,
        )

        WriteAction.runAndWait<Throwable> {
            CreatorTemplateProcessor.reformatAndOpenFiles(project, generatedFiles)
        }
    }
}
