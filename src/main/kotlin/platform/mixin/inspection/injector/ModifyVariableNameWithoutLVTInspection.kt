package com.demonwav.mcdev.platform.mixin.inspection.injector

import com.demonwav.mcdev.platform.mixin.inspection.MixinInspection
import com.demonwav.mcdev.platform.mixin.util.LocalInfo
import com.demonwav.mcdev.platform.mixin.util.MixinConstants.Annotations.MODIFY_VARIABLE
import com.demonwav.mcdev.platform.mixin.util.hasMissingLVT
import com.demonwav.mcdev.platform.mixin.util.mixinTargets
import com.demonwav.mcdev.util.findAnnotation
import com.demonwav.mcdev.util.findContainingClass
import com.intellij.codeInspection.ProblemsHolder
import com.intellij.psi.JavaElementVisitor
import com.intellij.psi.PsiAnnotation
import com.intellij.psi.PsiElement
import com.intellij.psi.PsiMethod
import com.intellij.util.ThreeState

class ModifyVariableNameWithoutLVTInspection : MixinInspection() {
    override fun buildVisitor(holder: ProblemsHolder) = object : JavaElementVisitor() {
        override fun visitMethod(method: PsiMethod) {
            val modifyVariable = method.findAnnotation(MODIFY_VARIABLE) ?: return
            val localType = method.parameterList.getParameter(0)?.type ?: return
            val localInfo = LocalInfo.fromAnnotation(localType, modifyVariable)

            val problemElement = Util.getProblemElement(localInfo, modifyVariable, modifyVariable) ?: return
            holder.registerProblem(
                problemElement,
                "@ModifyVariable uses a variable name, but the target class has no local variable names at runtime",
            )
        }
    }

    object Util {
        private val GENERATED_NAME_REGEX = Regex("(?:arg|var)\\d+")

        fun getProblemElement(
            localInfo: LocalInfo,
            localAnnotation: PsiAnnotation,
            injectorAnnotation: PsiAnnotation,
        ): PsiElement? {
            // names generated by Mixin don't depend on the local variable table
            if (localInfo.names.all { GENERATED_NAME_REGEX.matches(it) }) {
                return null
            }

            val mixinTargets = injectorAnnotation.findContainingClass()?.mixinTargets ?: return null
            val isMissingLVT = mixinTargets.any {
                injectorAnnotation.hasMissingLVT(it.name.replace('/', '.')) == ThreeState.YES
            }
            if (!isMissingLVT) {
                return null
            }

            return localAnnotation.findDeclaredAttributeValue("name") ?: localAnnotation.nameReferenceElement
        }
    }
}
